import Overview from '@/components/dashboard-layout/overview';
import type { Metadata } from 'next';
import { getTranslations } from 'next-intl/server';

export const generateMetadata = async ({
  params,
}: {
  params: Promise<{ locale: string }>;
}): Promise<Metadata> => {
  const { locale } = await params;
  const t = await getTranslations({ locale });
  const tLayout = await getTranslations({ locale, namespace: 'layout' });

  const SITE_URL =
    process.env.NEXT_PUBLIC_SITE_URL || 'https://nhatcapdang.com';

  const title = t('overview') || 'Overview';
  const description =
    t('enterprise_grade_token_management_platform') ||
    'Enterprise-grade token management platform';
  const url = `${SITE_URL}/dashboard`;

  // Canonical should point to the current page's URL
  const canonicalPath = '/dashboard';

  return {
    title,
    description,
    alternates: {
      canonical: canonicalPath,
      languages: {
        'x-default': canonicalPath,
        en: canonicalPath,
        vi: '/vi/dashboard',
      },
    },
    openGraph: {
      title,
      description,
      url,
      siteName: tLayout('title') || 'NhatCapDang',
      images: [
        {
          url: '/svgs/nhatcapdang.svg',
          width: 1200,
          height: 630,
          alt: title,
        },
      ],
      locale,
      type: 'website',
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: ['/svgs/nhatcapdang.svg'],
    },
  };
};

export default function Page() {
  return <Overview />;
}
